"""Audit generated HTML, sitemaps, and local resources. Python standard library only."""
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlparse, unquote
import json
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1] / "build"
errors = []

class Page(HTMLParser):
    def __init__(self):
        super().__init__()
        self.meta, self.links, self.resources, self.schemas = {}, [], [], []
        self.h1 = 0
        self.in_schema = False
        self.schema = ""
        self.title, self.in_title = "", False
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "title":
            self.in_title = True
        if tag == "meta":
            key = a.get("name", a.get("property"))
            if key:
                self.meta.setdefault(key, []).append(a.get("content", ""))
        if tag == "link":
            self.links.append(a)
            if a.get("rel") in ["stylesheet", "icon", "apple-touch-icon"]:
                self.resources.append(a.get("href", ""))
        if tag in ["script", "img"] and "src" in a:
            self.resources.append(a["src"])
        if tag == "h1":
            self.h1 += 1
        if tag == "script" and a.get("type") == "application/ld+json":
            self.in_schema, self.schema = True, ""
    def handle_data(self, data):
        if self.in_title:
            self.title += data
        if self.in_schema:
            self.schema += data
    def handle_endtag(self, tag):
        if tag == "title":
            self.in_title = False
        if tag == "script" and self.in_schema:
            self.schemas.append(json.loads(self.schema))
            self.in_schema = False

def is_phone_twin(p):
    rel = p.relative_to(root).as_posix()
    return rel.startswith(("m/", "en/m/")) or rel in ("m.html", "en/m.html")


all_pages = [p for p in root.rglob("*.html") if p.name != "404.html"]
pages = [p for p in all_pages if not is_phone_twin(p)]
# The phone shell under /m/ duplicates the desktop pages: it must stay out of the index and point at its desktop twin.
for p in all_pages:
    if not is_phone_twin(p):
        continue
    twin = Page()
    twin.feed(p.read_text(encoding="utf-8"))
    if "noindex" not in ",".join(twin.meta.get("robots", [])):
        errors.append(f"{p.relative_to(root)}: phone page must be noindex")
    if not [a for a in twin.links if a.get("rel") == "canonical"]:
        errors.append(f"{p.relative_to(root)}: phone page missing canonical")
canonicals = set()
titles = {}
VERIFICATION = "t5EgGuNWZ2_VdsT5X_pp0RWlqX2OqJ2vcy3zYHcOoPE"
descriptions = {}
for p in pages:
    page = Page()
    page.feed(p.read_text(encoding="utf-8"))
    def check(ok, message):
        if not ok:
            errors.append(f"{p.relative_to(root)}: {message}")
    check(page.h1 == 1, f"expected one h1, got {page.h1}")
    for key in ["description", "og:title", "og:description", "og:image", "og:url", "og:type", "og:site_name", "twitter:card", "twitter:title", "twitter:description", "twitter:image", "keywords"]:
        check(len(page.meta.get(key, [])) == 1 and bool(page.meta[key][0].strip()), f"missing/duplicate {key}")
    # /m/ pages are noindex twins of the desktop pages; their descriptions are not search snippets.
    indexable = "noindex" not in ",".join(page.meta.get("robots", []))
    if indexable and len(page.meta.get("description", [])) == 1:
        text = page.meta["description"][0].strip()
        floor = 40 if p.relative_to(root).parts[0] == "en" else 20  # CJK carries more per character
        check(floor <= len(text) <= 175, f"description length {len(text)} outside {floor}-175: {text[:40]!r}")
        descriptions.setdefault((p.relative_to(root).parts[0] == "en", text), []).append(p.relative_to(root).as_posix())
    if indexable:
        rel = p.relative_to(root).as_posix()
        is_home = rel in ["index.html", "en/index.html"]
        # A <title> is the search result headline: unique per page, and short enough not to be cut (CJK counts double).
        title = page.title.strip()
        titles.setdefault(title, []).append(rel)
        check(sum(2 if ord(c) > 0x2E80 else 1 for c in title) <= 62, f"title too long for a search result: {title!r}")
        check(page.meta.get("google-site-verification") == [VERIFICATION], "missing Search Console verification tag")
        # Every documentation page carries its own share card, generated by scripts/generate-social-cards.py.
        image = (page.meta.get("og:image") or [""])[0]
        check(is_home or "/img/social/" in image, f"og:image is not a per-page card: {image}")
        if "/img/social/" in image:
            check((root / image.split("cocoframework.dev/", 1)[1]).is_file(), f"share card missing: {image}")
        types ={t for s in page.schemas for t in ([s["@type"]] if isinstance(s["@type"], str) else s["@type"])}
        is_doc = p.relative_to(root).as_posix() not in ["index.html", "en/index.html"]
        check(not is_doc or "TechArticle" in types, "documentation page missing TechArticle schema")
        check(is_doc or "WebSite" in types, "home page missing WebSite schema")
    canonical = [a["href"] for a in page.links if a.get("rel") == "canonical"]
    check(len(canonical) == 1, "canonical missing/duplicate")
    if len(canonical) == 1:
        check(canonical[0] not in canonicals, "non-unique canonical")
        check(canonical[0].startswith("https://cocoframework.dev/"), "wrong canonical host")
        canonicals.add(canonical[0])
    languages = {a.get("hreflang") for a in page.links if a.get("rel") == "alternate"}
    check({"en", "zh-Hans"}.issubset(languages), "missing language alternates")
    for resource in page.resources:
        if resource.startswith("/"):
            check((root / unquote(urlparse(resource).path.lstrip("/"))).is_file(), f"missing resource {resource}")
        elif resource.startswith("http"):
            check(False, f"external page-load dependency {resource}")
    if p.relative_to(root).as_posix() in ["index.html", "en/index.html"]:
        check(any("SoftwareApplication" in s.get("@type", []) and s.get("programmingLanguage") == "Java" for s in page.schemas), "missing software schema")
for title, owners in titles.items():
    if len(owners) > 1:
        errors.append(f"duplicate title {title!r}: {', '.join(owners)}")
for (_, text), owners in descriptions.items():
    if len(owners) > 1:
        errors.append(f"duplicate description {text[:40]!r}: {', '.join(owners)}")
for sitemap in [root / "sitemap.xml", root / "en/sitemap.xml"]:
    doc = ET.parse(sitemap)
    for node in doc.findall(".//{*}loc"):
        if node.text not in canonicals:
            errors.append(f"sitemap URL missing canonical: {node.text}")
robots = (root / "robots.txt").read_text()
for url in ["https://cocoframework.dev/sitemap.xml", "https://cocoframework.dev/en/sitemap.xml"]:
    if f"Sitemap: {url}" not in robots:
        errors.append(f"robots missing {url}")
print(json.dumps({"pages": len(pages), "uniqueCanonicals": len(canonicals), "errors": errors}, ensure_ascii=False, indent=2))
raise SystemExit(bool(errors))
